#!/usr/bin/env python3
"""Generate offline location metadata from the vendored IANA and CLDR sources."""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
places = {}
for line in (root / 'ThirdParty/TimeZones/zone.tab').read_text().splitlines():
    if not line or line.startswith('#'):
        continue
    country, coordinate, identifier, *_ = line.split('\t')
    latitude, longitude = re.findall(r'[+-]\d+', coordinate)
    def angle(value, degree_digits):
        sign = -1 if value[0] == '-' else 1
        digits = value[1:]
        degrees = int(digits[:degree_digits])
        minutes = int(digits[degree_digits:degree_digits + 2])
        seconds = int(digits[degree_digits + 2:] or '0')
        return sign * (degrees + minutes / 60 + seconds / 3600)
    places[identifier] = (country, angle(latitude, 2), angle(longitude, 3))

aliases = {}
for line in (root / 'ThirdParty/TimeZones/backward').read_text().splitlines():
    tokens = line.split()
    if tokens and tokens[0] == 'Link':
        aliases[tokens[2]] = tokens[1]

def labels(language):
    tree = json.loads((root / f'ThirdParty/CLDR/timeZoneNames-{language}.json').read_text())
    zones = tree['main'][language]['dates']['timeZoneNames']['zone']
    result = {}
    def walk(node, path):
        if 'exemplarCity' in node:
            result['/'.join(path)] = node['exemplarCity']
        for key, value in node.items():
            if isinstance(value, dict):
                walk(value, path + [key])
    walk(zones, [])
    for identifier, value in list(result.items()):
        current, visited = identifier, set()
        while current not in places and current in aliases and current not in visited:
            visited.add(current)
            current = aliases[current]
        result.setdefault(current, value)
    return result

def quote(value):
    return json.dumps(value, ensure_ascii=False)

lines = [
    '// Generated by scripts/generate-world-regions.py. Do not edit by hand.',
    '// IANA tzdb 2026e (public domain); Unicode CLDR 91c267402229 (Unicode-3.0).',
    '// Full sources and licenses: ThirdParty/TimeZones and ThirdParty/CLDR.',
    'enum WorldRegionData {',
    '    static let places: [String: RegionLocation] = [',
]
for identifier, (country, lat, lon) in sorted(places.items()):
    lines.append(f'        {quote(identifier)}: .init(countryCode: {quote(country)}, latitude: {lat:.6f}, longitude: {lon:.6f}),')
lines += ['    ]', '    static let aliases: [String: String] = [']
for key, value in sorted(aliases.items()):
    lines.append(f'        {quote(key)}: {quote(value)},')
lines.append('    ]')
for language in ['en', 'zh']:
    lines.append(f'    static let {language}Names: [String: String] = [')
    for key, value in sorted(labels(language).items()):
        lines.append(f'        {quote(key)}: {quote(value)},')
    lines.append('    ]')
lines.append('}')
output = '\n'.join(lines) + '\n'
path = root / 'Sources/WorldRegionData.swift'
if '--check' in sys.argv:
    if not path.exists() or path.read_text() != output:
        raise SystemExit('WorldRegionData.swift is out of date; run scripts/generate-world-regions.py')
else:
    path.write_text(output)
print(f'World region metadata verified: {len(places)} locations, {len(aliases)} legacy identifiers.')
